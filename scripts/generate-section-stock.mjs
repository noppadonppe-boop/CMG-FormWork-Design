// Regenerates src/domain/sectionStock.ts — the stud / waler section catalogue used by the engine, optimizer and UI.
// Sources (all published gross properties, Thai market):
//   - src/reference/thai-sections/pap-tis107-2026.json  (scripts/extract-pap-tis107.mjs)  TIS 107 SHS / RHS / CHS, Pacific Pipe
//   - src/reference/thai-sections/sys-tis1227-2026.json (scripts/extract-sys-tis1227.mjs) TIS 1227 hot-rolled C and equal L, SYS
//   - src/reference/workflow-v07/sections.json: C-LIP (Pacific Pipe TIS 1228) and timber rectangles (actual dimensions)
//   - src/reference/workflow-v07/materials.json: timber classes from the user's textbook (Design Form Work, table 3.4)
// Usage: node scripts/generate-section-stock.mjs
import {readFileSync, writeFileSync} from 'node:fs';

const read = f => JSON.parse(readFileSync(f, 'utf8'));
const lib = read('src/reference/workflow-v07/sections.json'), mats = read('src/reference/workflow-v07/materials.json');
const pap = read('src/reference/thai-sections/pap-tis107-2026.json'), sys = read('src/reference/thai-sections/sys-tis1227-2026.json');
const rows = [];
const add = r => rows.push({...r, status: r.status ?? 'REVIEW_REQUIRED'});

// Timber studs: common Thai nominal-inch sizes, using the library's actual-dimension records (measure dressed size on site).
const TIMBER = [['38x75', '1½″×3″'], ['38x89', '1½″×3½″'], ['38x100', '1½″×4″'], ['50x50', '2″×2″'], ['50x75', '2″×3″'], ['50x100', '2″×4″'], ['75x75', '3″×3″'], ['75x100', '3″×4″']];
for (const [mm, inch] of TIMBER) {
  const s = lib.sections.find(x => x.section_id === `TIMBER-${mm}-ACTUAL`); if (!s) throw Error('timber ' + mm);
  add({id: s.section_id, designation: `ไม้ ${inch} (${s.B_mm}×${s.H_mm} mm)`, family: 'TIMBER', roles: ['stud'], B: s.B_mm, H: s.H_mm, t: 0,
    A_cm2: s.A_cm2, Ix_cm4: s.Ix_cm4, Sx_cm3: s.Sx_cm3, kg_per_m: null, source: 'BASE-V0.3', url: null, status: s.structural_design_status});
}
// TIS 107 tubes (practical formwork range).
for (const s of pap.sections) {
  const base = {source: pap.source.source_id, url: pap.source.url, ref: `${s.table} p${s.pdf_page}`, kg_per_m: s.kg_per_m, A_cm2: s.A_cm2};
  if ((s.family === 'SHS' || s.family === 'RHS') && s.t_mm >= 1.4 && s.H_mm <= 200 && s.B_mm >= 25)
    add({...base, id: `PAP-TIS107-${s.family}-${s.H_mm}x${s.B_mm}x${s.t_mm}`, designation: s.designation, family: s.family, roles: ['stud', 'waler'], B: s.B_mm, H: s.H_mm, t: s.t_mm, Ix_cm4: s.Ix_cm4, Sx_cm3: s.Sx_cm3});
  if (s.family === 'CHS' && s.t_mm >= 1.6 && s.D_mm >= 21.7 && s.D_mm <= 139.8)
    add({...base, id: `PAP-TIS107-CHS-${s.D_mm}x${s.t_mm}`, designation: `${s.designation} (${s.nps})`, family: 'CHS', roles: ['waler'], B: s.D_mm, H: s.D_mm, t: s.t_mm, D: s.D_mm, Ix_cm4: s.I_cm4, Sx_cm3: s.S_cm3});
}
// TIS 1227 hot-rolled channels and equal angles (SYS).
for (const s of sys.sections) {
  const base = {source: sys.source.source_id, url: sys.source.url, ref: `${s.table} p${s.pdf_page}`, kg_per_m: s.kg_per_m, A_cm2: s.A_cm2};
  if (s.family === 'C' && s.H_mm <= 250)
    add({...base, id: `SYS-TIS1227-C-${s.H_mm}x${s.B_mm}x${s.tw_mm}x${s.tf_mm}`, designation: s.designation, family: 'C', roles: ['waler'], B: s.B_mm, H: s.H_mm, t: s.tw_mm, tw: s.tw_mm, tf: s.tf_mm, Ix_cm4: s.Ix_cm4, Sx_cm3: s.Sx_cm3});
  if (s.family === 'L' && s.H_mm <= 150)
    add({...base, id: `SYS-TIS1227-L-${s.H_mm}x${s.B_mm}x${s.t_mm}`, designation: s.designation, family: 'L', roles: ['waler'], B: s.B_mm, H: s.H_mm, t: s.t_mm, Ix_cm4: s.Ix_cm4, Sx_cm3: s.Sx_min_cm3, Cy_cm: s.Cy_cm});
}
// Cold-formed lipped channels (Pacific Pipe TIS 1228) from the library, selectable rows only.
for (const s of lib.sections.filter(x => x.family === 'C_LIP' && x.candidate_selectable === true))
  add({id: s.section_id, designation: s.designation, family: 'C_LIP', roles: ['waler'], B: s.B_mm, H: s.H_mm, t: s.t_mm, lip: s.C_lip_mm,
    A_cm2: s.A_cm2, Ix_cm4: s.Ix_cm4, Sx_cm3: s.Sx_cm3, kg_per_m: s.kg_per_m, source: s.source_id, url: s.source_url, ref: `TIS 1228 p${s.source_pdf_page}`, status: s.structural_design_status});

const ids = new Set(); for (const r of rows) {if (ids.has(r.id)) throw Error('duplicate ' + r.id); ids.add(r.id);}
const grades = mats.materials.filter(m => m.material_id.startsWith('TIMBER-BOOK-')).map(m => ({id: m.material_id, label: m.grade_or_product,
  E: m.properties.E_ref_MPa, Fb: m.properties.Fb_base_MPa, Fv: m.properties.Fv_base_MPa, raw_ksc: m.raw_source_values_kgf_cm2, source: m.standard}));
const SOURCES = [pap.source, sys.source].map(({source_id, title, url, retrieved_on, pdf_sha256}) => ({source_id, title, url, retrieved_on, pdf_sha256}));

const out = `/** Stud / waler section catalogue generated by scripts/generate-section-stock.mjs. Do not edit by hand.
 * Thai-market sources with published gross properties (A, Ix, Sx = elastic modulus, kg/m):
 *  - TIS 107-2566 SHS / RHS / CHS (Pacific Pipe catalogue 2026_2, JIS G3466 / G3444 tables), STKR400 / STK400 Fy 245 MPa
 *  - TIS 1227-2558 hot-rolled channel C and equal angle L (SYS Engineer Handbook Edit 6), SS400 Fy 245 MPa
 *  - TIS 1228 cold-formed lipped channel C-LIP (Pacific Pipe, via the user's section library v${lib.metadata.library_version})
 *  - Timber rectangles, actual dimensions (user's section library) with timber classes from "Design Form Work" table 3.4 (อ้าง ว.ส.ท.)
 * Gross properties are not effective-section capacities; angle Sx is the minimum modulus about the geometric axis. */
import type {SectionProperties} from './mechanics.js';
export type StockFamily = 'TIMBER' | 'SHS' | 'RHS' | 'CHS' | 'L' | 'C' | 'C_LIP';
export type StockRole = 'stud' | 'waler';
export interface StockSection {id: string; designation: string; family: StockFamily; roles: StockRole[]; B: number; H: number; t: number;
  tw?: number; tf?: number; lip?: number; D?: number; Cy_cm?: number; A_cm2: number; Ix_cm4: number; Sx_cm3: number; kg_per_m: number | null;
  source: string; url: string | null; ref?: string; status: string}
export interface TimberGrade {id: string; label: string; E: number; Fb: number; Fv: number | null; raw_ksc: Record<string, number | null>; source: string}
export const SECTION_LIBRARY_VERSION = ${JSON.stringify(lib.metadata.library_version)};
export const SECTION_SOURCES = ${JSON.stringify(SOURCES, null, 1)};
export const TIMBER_GRADES: TimberGrade[] = ${JSON.stringify(grades, null, 1)};
export const SECTION_STOCK: StockSection[] = [
${rows.map(r => '  ' + JSON.stringify(r)).join(',\n')},
];
export const FAMILY_LABEL: Record<StockFamily, string> = {TIMBER: 'ไม้ (Timber)', SHS: 'เหล็กกล่องสี่เหลี่ยมจัตุรัส (SHS)', RHS: 'เหล็กกล่องสี่เหลี่ยมผืนผ้า (RHS)',
  CHS: 'เหล็กท่อกลม (CHS)', L: 'เหล็กฉาก (L)', C: 'เหล็กรางน้ำ (C รีดร้อน)', C_LIP: 'เหล็กตัวซี (C-LIP)'};
/** Engine walerType for each waler family (SHS and RHS are both box sections). */
export const WALER_TYPE = {SHS: 'RHS', RHS: 'RHS', CHS: 'CHS', L: 'L', C: 'C', C_LIP: 'C'} as const;
export const isChannel = (s: StockSection) => s.family === 'C' || s.family === 'C_LIP';
export const isTimber = (s: StockSection) => s.family === 'TIMBER';
const byId = new Map(SECTION_STOCK.map(s => [s.id, s]));
export const sectionById = (id: string) => byId.get(id);
export const sectionsFor = (role: StockRole, family?: StockFamily) => SECTION_STOCK.filter(s => s.roles.includes(role) && (!family || s.family === family));
export const timberGrade = (id: string) => TIMBER_GRADES.find(g => g.id === id);
/** Published gross properties in mm units. Shear area: web(s) for box/channel/angle, A/2 for a round tube, A/1.5 for a timber rectangle. */
export function catalogueProperties(s: StockSection): SectionProperties {
  const area = s.A_cm2 * 100;
  const shearArea = s.family === 'SHS' || s.family === 'RHS' ? 2 * s.t * (s.H - 2 * s.t) : s.family === 'CHS' ? area / 2 : s.family === 'L' ? s.t * s.H
    : s.family === 'C' ? s.tw! * (s.H - 2 * s.tf!) : s.family === 'C_LIP' ? s.t * (s.H - 2 * s.t) : area / 1.5;
  return {area, I: s.Ix_cm4 * 1e4, S: s.Sx_cm3 * 1e3, shearArea};
}
/** Project setting: ids of library sections the company stocks. Undefined = whole library allowed. Unknown ids are dropped. */
export function parseSectionStock(raw: unknown): string[] | undefined {
  if (!Array.isArray(raw)) return undefined;
  return raw.filter((v): v is string => typeof v === 'string' && byId.has(v));
}
export const stockFor = (ids: string[] | undefined) => ids ? SECTION_STOCK.filter(s => ids.includes(s.id)) : SECTION_STOCK;
`;
writeFileSync('src/domain/sectionStock.ts', out);
const count = f => rows.filter(r => r.family === f).length;
console.log(`sectionStock.ts: ${rows.length} sections — ${['TIMBER', 'SHS', 'RHS', 'CHS', 'L', 'C', 'C_LIP'].map(f => f + ' ' + count(f)).join(', ')}; timber grades ${grades.length}`);
